'use strict';
const assert = require('node:assert/strict');
const { app } = require('./helpers/app-harness.cjs');
const click = element => element.onclick({preventDefault(){}});
const read = (h, id) => h.query(id).textContent;
const first = 'practice-wa-video-2025-heima-pandas-io';
const second = 'practice-wa-video-2025-heima-pandas-filter';
const time = '2026-11-17T00:00:00Z';

(async () => {
  let h = app({now:time});
  let ctx = h.ctx;
  try {
    await ctx.AppProgress.sync().start();
    assert.equal(ctx.AppNavigation.route(),'home');
    assert.equal(h.query('#workspace').hidden,true);
    assert.equal(h.query('#learningPath').hidden,true);
    assert.match(read(h,'#learningTodayTitle'),/读取和保存表格/);
    assert.match(read(h,'#learningTodayCheck'),/8 条/);
    assert.equal(read(h,'#learningWeekTitle'),'用 Python 筛选、去重和统计表格。');
    assert.equal(h.query('#learningTodayVideo').getAttribute('href'),'https://www.bilibili.com/video/BV1sHU9BmEne/?p=142');
    assert.equal(read(h,'#learningPackCount'),'必做已完成 0 / 2 项');
    assert.equal(h.all('#learningPackRows li').length,3);
    assert.equal(h.all('#learningStageTable tbody tr').length,4);
    const stage = suffix => h.query('[data-progress-stage="wa-m0"] ' + suffix).textContent;
    assert.equal(stage('.lh-stage-count'),'0 / 3');
    assert.match(stage('.lh-stage-next'),/读取和保存表格/);
    const watch = h.query('[data-home-lesson="watch-wa-video-2025-heima-pandas-io"]');
    watch.checked = true; watch.onchange();
    assert.equal(read(h,'#learningPackCount'),'必做已完成 0 / 2 项');
    assert.equal(ctx.AppProgress.sync().lessonSnapshot()[first], undefined);
    assert.equal(stage('.lh-stage-count'),'0 / 3');
    watch.checked = false; watch.onchange();
    const homeFirst = h.query('[data-home-lesson="'+first+'"]');
    homeFirst.checked = true; homeFirst.onchange();
    assert.equal(read(h,'#learningPackCount'),'必做已完成 1 / 2 项');
    assert.equal(stage('.lh-stage-count'),'1 / 3');
    assert.match(stage('.lh-stage-next'),/筛选表格/);
    assert.equal(h.all('#learningPackRows li').length,3);
    const homeSecond = h.query('[data-home-lesson="'+second+'"]');
    homeSecond.checked = true; homeSecond.onchange();
    assert.equal(read(h,'#learningPackCount'),'必做已完成 0 / 1 项');
    assert.equal(h.all('#learningPackRows li').length,1);
    assert.equal(h.query('#learningPackRows a').textContent,'去验收');
    assert.equal(stage('.lh-stage-count'),'2 / 3');
    assert.equal(ctx.LearningHome.dailyPack(ctx.UnifiedTasks.registry()).required[0].kind,'delivery');
    ctx.UnifiedTasks.saveLesson(second,false);
    ctx.UnifiedTasks.saveLesson(first,false);
    assert.equal(stage('.lh-stage-count'),'0 / 3');
    assert.equal(read(h,'#learningPackCount'),'必做已完成 0 / 2 项');

    assert(h.query('#learningTodaySteps').hidden);
    h.query('#learningTodayStepsButton').onclick();
    assert.equal(h.query('#learningTodayStepsButton').getAttribute('aria-expanded'),'true');
    assert.equal(h.all('#learningTodayStepsList li').length,3);
    h.query('#learningTodayStepsButton').onclick();
    assert(h.query('#learningTodaySteps').hidden);
    h.query('#learningTodayStepsButton').onclick();
    click(h.query('#learningTodayRecord'));
    assert.equal(ctx.AppNavigation.route(),'execution');
    assert(h.query('[data-unified-row="lesson:'+first+'"]').open);
    const record = h.query('[data-unified-lesson="'+first+'"]');
    record.checked = true; record.onchange();
    assert.equal(ctx.AppProgress.sync().lessonSnapshot()[first], 'done');
    assert.equal(ctx.AppProgress.sync().lessonSnapshot()['watch-wa-video-2025-heima-pandas-io'], false);
    ctx.location.hash = ''; ctx.dispatchEvent({type:'popstate'});
    assert.equal(ctx.AppNavigation.route(),'home');
    assert.match(read(h,'#learningTodayTitle'),/筛选/);
    assert(h.query('#learningSamplePreview').hidden);
    assert(h.query('#learningTodaySteps').hidden);
    click(h.query('#learningHome [data-home-route="path"]'));
    assert.equal(ctx.AppNavigation.route(),'path');
    assert(h.query('[data-home-stage="wa-m0"]').classList.contains('lh-path-current'));
    assert.equal(h.all('[data-home-stage]').length,4);
    const memory = h.memory; h.destroy();
    h=app({memory,now:time,hash:'#home'});ctx=h.ctx;
    await ctx.AppProgress.sync().start();
    assert.match(read(h,'#learningTodayTitle'),/筛选/);
    h.query('#learningTodayStepsButton').onclick();
    assert(h.query('[data-unified-row="lesson:'+second+'"]').open);
    const undo = h.query('[data-unified-lesson="'+first+'"]');
    undo.checked = false; undo.onchange();
    click(h.query('#mainTabs [data-site-route="home"]'));
    assert.match(read(h,'#learningTodayTitle'),/读取和保存表格/);
    const remaining = ctx.UnifiedTasks.registry().filter(x=>['practice','delivery'].includes(x.kind));
    assert.equal(remaining.length,11);
    assert.equal(ctx.LearningHome.select(remaining.map(x=>({...x,done:true}))),null);
    console.log('PASS focused home, 3 goal levels, optional exact video, durable independent completion and undo, original routes, 4-step path');
  } finally { h.destroy(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
