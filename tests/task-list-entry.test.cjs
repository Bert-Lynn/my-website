'use strict';
const assert = require('node:assert/strict');
const { app } = require('./helpers/app-harness.cjs');
const plain = value => JSON.parse(JSON.stringify(value));
const click = node => { assert(node, 'click target exists'); assert.equal(typeof node.onclick, 'function'); return node.onclick({ preventDefault() {}, currentTarget: node }); };
const now = '2026-11-10T00:00:00.000Z';
const inputFor = (h, id) => h.query('#taskGroups [data-id="' + id + '"]');

(async () => {
  let h = app({ now }), ctx = h.ctx;
  await ctx.AppProgress.sync().start();
  assert.equal(ctx.AppNavigation.current(), 'execution', 'bare URL opens the B task workspace directly');
  click(h.query('#enterWorkspace'));
  assert.equal(ctx.AppNavigation.current(), 'modules', 'the cover CTA opens the module chooser');
  click(h.query('[data-hub-route="execution"]'));
  assert.equal(ctx.AppNavigation.current(), 'execution', 'the overall-task card opens actual tasks');
  assert.equal(ctx.AppNavigation.route(), 'execution');
  assert.equal(h.query('#currentTaskList').hidden, false);
  assert.equal(h.all('#currentTaskList [data-current-task]').length, 4, 'default entry exposes the current four concrete WA tasks');
  assert.equal(h.query('#originalTaskPlan').hidden, true);
  click(h.query('[data-task-section="execution/month"]'));
  assert.equal(ctx.AppNavigation.route(), 'execution/month');
  assert.equal(h.query('#workspace').hidden, false);
  assert.equal(h.query('#today').hidden, true, 'career explanation does not replace the task list');
  const mainNav = h.query('#mainTabs');
  const taskNav = mainNav.querySelector('[data-page="execution"]');
  assert(taskNav, 'task list is directly available in the primary navigation');
  assert.equal(mainNav.querySelectorAll('[data-page]')[0], taskNav, 'task list is the first primary tab');
  assert.equal(taskNav.getAttribute('aria-label'), '任务列表');
  assert(h.query('#taskGroups').textContent.includes('2026.11'), 'current month tasks render immediately');
  assert(h.query('#taskGroups').textContent.includes('顺延'), 'unfinished prior tasks remain visible without another click');
  const currentIds = h.evaluate('tasks.filter(t => t.month <= currentMonth()).map(t => t.id)');
  assert.deepEqual(h.all('#taskGroups [data-id]').map(node => node.dataset.id).sort(), plain(currentIds).sort());
  assert.equal(h.evaluate('tasks.length'), 47);
  const target = h.query('.is-backlog [data-id]'); assert(target, 'a carried task is actually actionable');
  const id = target.dataset.id;
  const beforeCareer = plain(ctx.phdCareerProgress.read());
  target.checked = true; target.onchange();
  assert.equal(ctx.AppProgress.sync().snapshot()[id], true);
  const completedAt = ctx.AppProgress.sync().taskCompletedAtSnapshot()[id]; assert(completedAt);
  assert.equal(h.evaluate('tally(tasks).done'), 1);
  assert.equal(ctx.LessonUI.stats().done, 0);
  assert.equal(ctx.CareerUI.stats().lessons.done, 0);
  assert.deepEqual(plain(ctx.phdCareerProgress.read()), beforeCareer, 'task completion does not grant course, skill or new project completion');
  const memory = h.memory; h.destroy();
  h = app({ memory, hash: '#execution/month', now }); ctx = h.ctx; await ctx.AppProgress.sync().start();
  assert.equal(ctx.AppNavigation.current(), 'execution', 'explicit task-route reload returns directly to tasks');
  assert.equal(inputFor(h, id).checked, true, 'historical completion is accessible and retained');
  assert.equal(ctx.AppProgress.sync().taskCompletedAtSnapshot()[id], completedAt);
  inputFor(h, id).checked = false; inputFor(h, id).onchange();
  assert.equal(ctx.AppProgress.sync().snapshot()[id], false);
  assert.equal(ctx.AppProgress.sync().taskCompletedAtSnapshot()[id], undefined);
  assert.equal(h.evaluate('tally(tasks).done'), 0);
  click(h.query('#viewTabs [data-view="year"]'));
  assert.equal(h.all('#taskGroups [data-id]').length, 47, 'all original task identities remain reachable');
  const picker = h.query('#monthPicker'); picker.value = '2027.11'; picker.onchange({ target: picker });
  assert.equal(h.all('#taskGroups [data-id]').length, 47, 'all unfinished tasks carry beyond the final plan month');
  assert.equal(h.evaluate('tally(tasks).done'), 0, 'calendar passage does not finish tasks');

  // Direct historical hashes and the new primary tab preserve their distinct destinations.
  ctx.AppNavigation.open('today'); assert.equal(h.query('#today').hidden, false); assert.equal(h.query('#workspace').hidden, true);
  click(h.query('#mainTabs [data-page="execution"]')); assert.equal(ctx.AppNavigation.current(), 'execution');
  assert.equal(h.query('#workspace').hidden, false);
  ctx.AppNavigation.open('execution');
  const projectForm = h.query('#currentTaskList [data-milestone-form="wa-m0"]'); assert(projectForm);
  projectForm.querySelector('[name="milestoneEvidence"]').value = 'https://example.com/unsaved-task-nav-qa'; projectForm.oninput();
  h.setConfirmation(false); click(h.query('#mainTabs [data-page="resources"]'));
  assert.equal(ctx.location.hash, '#execution');
  assert(h.query('#currentTaskList [data-milestone-form="wa-m0"]') === projectForm, 'Cancel retains the exact unfinished project form');
  h.setConfirmation(true); click(h.query('#mainTabs [data-page="resources"]'));
  assert.equal(ctx.AppNavigation.current(), 'resources');
  assert.equal(ctx.phdCareerProgress.read().milestones['work-assistant']?.['wa-m0'], undefined, 'discarded draft is never saved by navigation');
  click(h.query('#homeBtn')); assert.equal(ctx.AppNavigation.current(), 'modules', 'brand link returns to module selection');
  ctx.location.hash = ''; ctx.dispatchEvent({ type: 'popstate' });
  assert.equal(ctx.AppNavigation.current(), 'execution', 'empty hash during browser history returns to tasks');
  click(h.query('#enterWorkspace'));
  assert.equal(ctx.AppNavigation.current(), 'modules', 're-entering opens the chooser once');
  click(h.query('[data-hub-route="execution"]'));
  assert.equal(ctx.AppNavigation.current(), 'execution', 'choosing tasks returns to their real list');
  h.destroy();

  h = app({ memory, hash: '#execution', now }); ctx = h.ctx; await ctx.AppProgress.sync().start();
  assert.equal(ctx.AppNavigation.current(), 'execution');
  assert.equal(ctx.AppProgress.sync().snapshot()[id], false, 'undo remains saved after explicit task-link reload');
  assert.equal(ctx.AppProgress.sync().taskCompletedAtSnapshot()[id], undefined);
  h.destroy();
  console.log('PASS current-task workspace: cover-to-hub-to-WA4 entry, explicit historical month reload, first primary task tab, real current/carried tasks, all47 after plan end, explicit done/undo/date/reload, independent records, dirty-form guard, and brand navigation.');
})().catch(error => { console.error(error); process.exitCode = 1; });
