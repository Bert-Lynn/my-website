const assert = require('node:assert/strict');
const { app } = require('./helpers/app-harness.cjs');
const plain = value => JSON.parse(JSON.stringify(value));
const sameNode = (actual, expected, message = 'same draft DOM node is retained') => assert(actual === expected, message);
const submit = form => form.onsubmit({ preventDefault() {}, currentTarget: form });
const setForm = (form, status, evidence, checked = false) => {
  form.querySelector('[name="milestoneStatus"]').value = status;
  form.querySelector('[name="milestoneEvidence"]').value = evidence;
  form.querySelector('[name="milestoneAttest"]').checked = checked;
};
const newRecord = (ctx, id) => ctx.phdCareerProgress.read().milestones['ai-choice-assistant']?.[id];
const moduleForm = h => h.query('.module-project-output [data-project-id="ai-choice-assistant"]');

(async () => {
  const oldDate = '2026-10-01T08:00:00.000Z';
  const oldRecord = { status: 'done', evidenceUrl: 'https://example.com/legacy-project-evidence', completedAt: oldDate };
  let h = app({ memory: { 'lin-ai-phd-roadmap-career-v1': JSON.stringify({ 'milestone:demand-decision-lab:ddl-m0': oldRecord }) } });
  let { ctx } = h; await ctx.AppProgress.sync().start();
  assert.equal(ctx.phdCareerProgress.read().selectedRole, 'agent_engineering');
  assert.equal(ctx.CareerUI.mainProject().id, 'ai-choice-assistant');
  assert.deepEqual(plain(ctx.CareerUI.mainProjectStats()), { done: 0, total: 6 }, 'old project progress cannot become new project progress');
  assert.deepEqual(plain(ctx.phdCareerProgress.read().milestones['demand-decision-lab']['ddl-m0']), oldRecord);
  const stages = ctx.CareerUI.mainProject().milestones;
  assert.deepEqual(plain(stages.map(stage => stage.moduleId)), plain(ctx.CareerUI.modules().map(module => module.id)), 'one new output stage per Agent learning module in order');
  assert.deepEqual(h.all('.current-project-progress [data-milestone-form]').map(form => form.dataset.milestoneForm), Array.from({ length: 6 }, (_, i) => 'aca-m' + i));
  assert.equal(h.all('.legacy-project-plan [data-milestone-form]').length, 7);
  for (const stage of stages) {
    ctx.AppNavigation.open('learn/' + stage.moduleId);
    assert.equal(h.all('#careerLearning [data-milestone-form]').length, 1, 'focused module contains exactly its one output stage');
    const form = moduleForm(h); assert(form); assert.equal(form.dataset.milestoneForm, stage.id);
    assert.equal(form.dataset.projectId, 'ai-choice-assistant');
    assert.equal(form.querySelector('[name="milestoneStatus"]').value, 'todo');
    assert.equal(h.query('.module-project-output').querySelectorAll('li').length, stage.deliverables.length + stage.acceptance.length);
    assert.equal(newRecord(ctx, stage.id), undefined, 'reading an output stage cannot create completion');
  }
  ctx.AppNavigation.open('learn/code');
  let form = moduleForm(h);
  setForm(form, 'done', '', false); submit(form);
  assert(form.querySelector('.form-error').textContent.includes('证据')); assert.equal(newRecord(ctx, 'aca-m0'), undefined);
  setForm(form, 'done', 'javascript:alert(1)', true); submit(form); assert.equal(newRecord(ctx, 'aca-m0'), undefined);
  setForm(form, 'done', 'https://example.com/assistant-code', false); submit(form); assert.equal(newRecord(ctx, 'aca-m0'), undefined, 'a URL without attestations does not complete the project stage');
  setForm(form, 'done', 'https://example.com/assistant-code', true); submit(form);
  const completedAt = newRecord(ctx, 'aca-m0').completedAt; assert(completedAt);
  assert.deepEqual(plain(ctx.CareerUI.mainProjectStats()), { done: 1, total: 6 });
  assert.deepEqual(plain(ctx.phdCareerProgress.read().milestones['demand-decision-lab']['ddl-m0']), oldRecord);
  assert.equal(ctx.CareerUI.stats().lessons.done, 0); assert.equal(ctx.CareerUI.stats().skillsPassed, 0);
  assert.equal(ctx.LessonUI.stats().done, 0); assert.equal(h.evaluate('tally(tasks).done'), 0);
  assert(h.query('.home-project-progress').textContent.includes('1 / 6'));
  form = moduleForm(h); submit(form); assert.equal(newRecord(ctx, 'aca-m0').completedAt, completedAt, 'repeat save keeps actual date');
  const memory = h.memory; h.destroy(); h = app({ memory, hash: '#learn/code' }); ctx = h.ctx; await ctx.AppProgress.sync().start();
  assert.equal(newRecord(ctx, 'aca-m0').completedAt, completedAt, 'new-project completion survives deep-link reload');
  form = moduleForm(h); assert.equal(form.querySelector('[name="milestoneStatus"]').value, 'done');
  setForm(form, 'todo', 'https://example.com/assistant-code', false); submit(form);
  assert.equal(newRecord(ctx, 'aca-m0').completedAt, ''); assert.equal(ctx.CareerUI.mainProjectStats().done, 0);
  assert.equal(ctx.phdCareerProgress.read().milestones['demand-decision-lab']['ddl-m0'].completedAt, oldDate);
  h.destroy(); h = app({ memory, hash: '#learn/code' }); ctx = h.ctx; await ctx.AppProgress.sync().start();
  assert.equal(newRecord(ctx, 'aca-m0').status, 'todo', 'new-project undo survives reload');
  ctx.AppNavigation.open('learn/data'); form = moduleForm(h);
  setForm(form, 'doing', 'https://example.com/unsaved-assistant-data'); form.oninput();
  ctx.CareerUI.render(); sameNode(moduleForm(h), form, 'background rendering preserves a module project draft');
  h.setConfirmation(false);
  const next = h.query('.module-navigation [data-open-module="check-results"]'); assert(next); next.onclick();
  assert.equal(ctx.location.hash, '#learn/data'); assert.equal(ctx.CareerUI.currentModule().id, 'data');
  sameNode(moduleForm(h), form); assert.equal(form.querySelector('[name="milestoneEvidence"]').value, 'https://example.com/unsaved-assistant-data');
  ctx.history.back(); assert.equal(ctx.location.hash, '#learn/data'); sameNode(moduleForm(h), form, 'Cancel restores hash and keeps draft after browser Back');
  assert.equal(ctx.CareerUI.openSkill('sql-data'), false); assert.equal(ctx.LessonUI.openLesson('python-basics'), false);
  const original = ctx.phdCareerProgress.setMilestone; ctx.phdCareerProgress.setMilestone = () => false;
  submit(form); assert(form.querySelector('.form-error').textContent.includes('未成功保存')); sameNode(moduleForm(h), form);
  assert.equal(ctx.AppNavigation.open('today'), false, 'failed save cannot silently clear the dirty guard');
  assert.equal(newRecord(ctx, 'aca-m1'), undefined);
  ctx.phdCareerProgress.setMilestone = original; submit(form);
  assert.equal(newRecord(ctx, 'aca-m1').status, 'doing'); assert.equal(newRecord(ctx, 'aca-m1').completedAt, '');
  assert.equal(ctx.AppNavigation.open('today'), true, 'successful save releases the dirty guard');
  ctx.phdCareerProgress.setRole('decision_optimization');
  assert.equal(ctx.CareerUI.mainProjectStats().done, 0); assert.equal(newRecord(ctx, 'aca-m1').status, 'doing', 'switching route does not erase new-project evidence');
  ctx.AppNavigation.open('learn/data'); assert.equal(h.all('#careerLearning [data-project-id="ai-choice-assistant"]').length, 0, 'legacy study route does not mislabel its old practice as the new project');
  ctx.AppNavigation.open('projects'); assert.equal(h.all('.current-project-progress [data-project-id="ai-choice-assistant"]').length, 6, 'new project stays accessible after a saved legacy-route choice');
  h.destroy();
  console.log('PASS independent assistant project UI: exact six module-stage bindings, old/new state separation, evidence/attestation gate, repeat dates, undo/reload, module draft cancel/history/failed-save guards, role retention, and no inferred lesson/task/skill completion.');
})().catch(error => { console.error(error); process.exitCode = 1; });
