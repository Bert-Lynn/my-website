const assert = require('node:assert/strict');
const { app: baseApp } = require('./helpers/app-harness.cjs');
// Career-specific regressions open the auxiliary development route explicitly.
const app = (options = {}) => baseApp({ hash: '#today', ...options });
const plain = value => JSON.parse(JSON.stringify(value));
const sameNode = (actual, expected, message = 'same draft DOM node is retained') => assert(actual === expected, message);
const submit = form => form.onsubmit({ preventDefault() {}, currentTarget: form });
const setForm = (form, status, evidence, checked = false) => {
  form.querySelector('[name="milestoneStatus"]').value = status;
  form.querySelector('[name="milestoneEvidence"]').value = evidence;
  form.querySelector('[name="milestoneAttest"]').checked = checked;
};
const newRecord = (ctx, id) => ctx.phdCareerProgress.read().milestones['work-assistant']?.[id];
const currentFlowId = h => h.query('.module-flow [aria-current="step"]')?.dataset.openModule;
const moduleForm = h => h.query('.module-project-output [data-project-id="work-assistant"]');

(async () => {
  const oldDate = '2026-10-01T08:00:00.000Z';
  const oldRecord = { status: 'done', evidenceUrl: 'https://example.com/legacy-project-evidence', completedAt: oldDate };
  let h = app({ memory: { 'lin-ai-phd-roadmap-career-v1': JSON.stringify({ 'milestone:demand-decision-lab:ddl-m0': oldRecord, 'milestone:ai-choice-assistant:aca-m0': { ...oldRecord, evidenceUrl:'https://example.com/old-aca-evidence' } }) } });
  let { ctx } = h; await ctx.AppProgress.sync().start();
  assert.equal(ctx.phdCareerProgress.read().selectedRole, 'agent_engineering');
  assert.equal(ctx.CareerUI.mainProject().id, 'work-assistant');
  assert.deepEqual(plain(ctx.CareerUI.mainProjectStats()), { done: 0, total: 4 }, 'old project progress cannot become new project progress');
  assert.equal(currentFlowId(h), 'code', 'old project progress cannot skip the first new output stage');
  assert.deepEqual(plain(ctx.phdCareerProgress.read().milestones['demand-decision-lab']['ddl-m0']), oldRecord);
  assert.equal(ctx.phdCareerProgress.read().milestones['ai-choice-assistant']['aca-m0'].status,'done','archived ACA completion keeps its original project identity');
  const stages = ctx.CareerUI.mainProject().milestones;
  assert.deepEqual(plain(stages.map(stage => stage.moduleId)), ['code','ai-tools','check-results','interview'], 'four outcome stages have explicit primary reference modules');
  assert.deepEqual(plain(stages.flatMap(stage => stage.moduleIds).sort()), plain(ctx.CareerUI.modules().map(module => module.id).sort()), 'all six reference modules map to exactly one of the four outcomes');
  assert.deepEqual(h.all('.current-project-progress [data-milestone-form]').map(form => form.dataset.milestoneForm), Array.from({ length: 4 }, (_, i) => 'wa-m' + i));
  assert.equal(h.all('.legacy-project-plan [data-milestone-form]').length, 7);
  assert.equal(h.all('.archived-assistant-plan [data-milestone-form]').length,6);
  for (const stage of stages) {
    ctx.AppNavigation.open('learn/' + stage.moduleId);
    assert.equal(h.all('#careerLearning [data-milestone-form]').length, 1, 'focused module contains exactly its one output stage');
    const form = moduleForm(h); assert(form); assert.equal(form.dataset.milestoneForm, stage.id);
    assert.equal(form.dataset.projectId, 'work-assistant');
    assert.equal(form.querySelector('[name="milestoneStatus"]').value, 'todo');
    for (const text of [...stage.deliverables,...stage.acceptance]) assert(h.query('.module-project-output').textContent.includes(text));
    assert.equal(newRecord(ctx, stage.id), undefined, 'reading an output stage cannot create completion');
  }
  for(const module of ctx.CareerUI.modules()) {
    ctx.AppNavigation.open('learn/'+module.id);
    const bound=moduleForm(h),stage=stages.find(s=>s.moduleIds.includes(module.id));assert(bound);assert.equal(bound.dataset.milestoneForm,stage.id,'every reference module uses its one real outcome identity');
  }
  ctx.AppNavigation.open('learn/code');
  let form = moduleForm(h);
  setForm(form, 'done', '', false); submit(form);
  assert(form.querySelector('.form-error').textContent.includes('证据')); assert.equal(newRecord(ctx, 'wa-m0'), undefined);
  setForm(form, 'done', 'javascript:alert(1)', true); submit(form); assert.equal(newRecord(ctx, 'wa-m0'), undefined);
  setForm(form, 'done', 'https://example.com/assistant-code', false); submit(form); assert.equal(newRecord(ctx, 'wa-m0'), undefined, 'a URL without attestations does not complete the project stage');
  setForm(form, 'done', 'https://example.com/assistant-code', true); submit(form);
  const completedAt = newRecord(ctx, 'wa-m0').completedAt; assert(completedAt);
  assert.deepEqual(plain(ctx.CareerUI.mainProjectStats()), { done: 1, total: 4 });
  assert.equal(currentFlowId(h), 'ai-tools', 'only explicit first-stage acceptance advances the new project recommendation');
  assert.deepEqual(plain(ctx.phdCareerProgress.read().milestones['demand-decision-lab']['ddl-m0']), oldRecord);
  assert.equal(ctx.CareerUI.stats().lessons.done, 0); assert.equal(ctx.CareerUI.stats().skillsPassed, 0);
  assert.equal(ctx.LessonUI.stats().done, 0); assert.equal(h.evaluate('tally(tasks).done'), 0);
  assert(h.query('.home-project-progress').textContent.includes('1 / 4'));
  ctx.AppNavigation.open('learn/data');assert.equal(moduleForm(h).querySelector('[name="milestoneStatus"]').value,'done','second reference module shares WA0 state without double-counting');assert.equal(ctx.CareerUI.mainProjectStats().done,1);
  ctx.AppNavigation.open('learn/code');
  form = moduleForm(h); submit(form); assert.equal(newRecord(ctx, 'wa-m0').completedAt, completedAt, 'repeat save keeps actual date');
  const memory = h.memory; h.destroy(); h = app({ memory, hash: '#learn/code' }); ctx = h.ctx; await ctx.AppProgress.sync().start();
  assert.equal(newRecord(ctx, 'wa-m0').completedAt, completedAt, 'new-project completion survives deep-link reload');
  assert.equal(currentFlowId(h), 'ai-tools', 'saved new-project recommendation survives reload');
  form = moduleForm(h); assert.equal(form.querySelector('[name="milestoneStatus"]').value, 'done');
  setForm(form, 'todo', 'https://example.com/assistant-code', false); submit(form);
  assert.equal(newRecord(ctx, 'wa-m0').completedAt, ''); assert.equal(ctx.CareerUI.mainProjectStats().done, 0);
  assert.equal(currentFlowId(h), 'code', 'undo restores the uncompleted first project recommendation');
  assert.equal(ctx.phdCareerProgress.read().milestones['demand-decision-lab']['ddl-m0'].completedAt, oldDate);
  h.destroy(); h = app({ memory, hash: '#learn/code' }); ctx = h.ctx; await ctx.AppProgress.sync().start();
  assert.equal(newRecord(ctx, 'wa-m0').status, 'todo', 'new-project undo survives reload');
  ctx.AppNavigation.open('learn/app'); form = moduleForm(h);
  setForm(form, 'doing', 'https://example.com/unsaved-assistant-data'); form.oninput();
  ctx.CareerUI.render(); sameNode(moduleForm(h), form, 'background rendering preserves a module project draft');
  h.setConfirmation(false);
  const next = h.query('.module-navigation [data-open-module="check-results"]'); assert(next); next.onclick();
  assert.equal(ctx.location.hash, '#learn/app'); assert.equal(ctx.CareerUI.currentModule().id, 'app');
  sameNode(moduleForm(h), form); assert.equal(form.querySelector('[name="milestoneEvidence"]').value, 'https://example.com/unsaved-assistant-data');
  ctx.history.back(); assert.equal(ctx.location.hash, '#learn/app'); sameNode(moduleForm(h), form, 'Cancel restores hash and keeps draft after browser Back');
  assert.equal(ctx.CareerUI.openSkill('sql-data'), false); assert.equal(ctx.LessonUI.openLesson('python-basics'), false);
  const original = ctx.phdCareerProgress.setMilestone; ctx.phdCareerProgress.setMilestone = () => false;
  submit(form); assert(form.querySelector('.form-error').textContent.includes('未成功保存')); sameNode(moduleForm(h), form);
  assert.equal(ctx.AppNavigation.open('today'), false, 'failed save cannot silently clear the dirty guard');
  assert.equal(newRecord(ctx, 'wa-m1'), undefined);
  ctx.phdCareerProgress.setMilestone = original; submit(form);
  assert.equal(newRecord(ctx, 'wa-m1').status, 'doing'); assert.equal(newRecord(ctx, 'wa-m1').completedAt, '');
  assert.equal(ctx.AppNavigation.open('today'), true, 'successful save releases the dirty guard');
  ctx.phdCareerProgress.setRole('decision_optimization');
  assert.equal(ctx.CareerUI.mainProjectStats().done, 0); assert.equal(newRecord(ctx, 'wa-m1').status, 'doing', 'switching route does not erase new-project evidence');
  ctx.AppNavigation.open('learn/data'); assert.equal(h.all('#careerLearning [data-project-id="work-assistant"]').length, 0, 'legacy study route does not mislabel its old practice as the new project');
  ctx.AppNavigation.open('projects'); assert.equal(h.all('.current-project-progress [data-project-id="work-assistant"]').length, 4, 'new project stays accessible after a saved legacy-route choice');
  const archived=h.query('.archived-assistant-plan [data-project-id="ai-choice-assistant"][data-milestone-form="aca-m0"]'); assert(archived,'archived ACA record has its own reachable form');
  setForm(archived,'todo','https://example.com/old-aca-evidence',false); submit(archived);
  assert.equal(ctx.phdCareerProgress.read().milestones['ai-choice-assistant']['aca-m0'].completedAt,'');
  assert.equal(ctx.phdCareerProgress.read().milestones['demand-decision-lab']['ddl-m0'].completedAt,oldDate);
  assert.equal(newRecord(ctx,'wa-m1').status,'doing','archive undo cannot mutate the current work project');
  const archivedAgain=h.query('.archived-assistant-plan [data-project-id="ai-choice-assistant"][data-milestone-form="aca-m0"]');
  setForm(archivedAgain,'done','https://example.com/old-aca-evidence',true); submit(archivedAgain);
  assert.equal(ctx.phdCareerProgress.read().milestones['ai-choice-assistant']['aca-m0'].status,'done');
  assert.equal(ctx.CareerUI.mainProjectStats().done,0,'archived save never completes a new outcome');
  h.destroy();
  console.log('PASS independent assistant project UI: four outcomes across six module bindings, old/new state separation, evidence/attestation gate, repeat dates, undo/reload, module draft cancel/history/failed-save guards, role retention, and no inferred lesson/task/skill completion.');
})().catch(error => { console.error(error); process.exitCode = 1; });
